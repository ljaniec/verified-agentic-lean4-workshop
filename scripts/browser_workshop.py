def render(task: Task, completed: bool) -> str:
    """Keep the full shared model unchanged; only its import is made portable."""
    header = (
        f"-- {task.title}\n"
        "-- Paste this ENTIRE file into https://live.lean-lang.org/\n"
        "-- Edit only the final proof. Definitions and theorem are fixed.\n"
        "-- Generated by scripts/browser_workshop.py; see course/browser/README.md.\n\n"
    )
    proof = task.proof if completed else task.starter
    if task.model is None:
        return header + "import Std\n\n" + task.declaration + proof
    model = (MODELS / f"{task.model}.lean").read_text(encoding="utf-8")
    model = model.replace("import Mathlib\n", "import Std\n", 1)
    closing = f"end VerifiedAgenticWorkshop.Scenarios.{task.model}"
    return header + model.replace(closing, task.declaration + proof + "\n" + closing)


def run(*args: str) -> subprocess.CompletedProcess[str]:
    result = subprocess.run(
        args,
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
        timeout=90,
        env={**os.environ, "NO_COLOR": "1"},
    )
    return result


def scan(path: Path) -> None:
    result = run("bash", str(ROOT / "scripts/check_forbidden_constructs.sh"), str(path))
    if result.returncode:
        raise RuntimeError(result.stdout + result.stderr)


def compile_file(path: Path) -> subprocess.CompletedProcess[str]:
    return run("lean", "-DwarningAsError=true", str(path))


def check_bundle() -> None:
    # Run plain Lean, not Lake: the event bundle must need no project packages.
    version = run("lean", "--version")
    if version.returncode:
        raise RuntimeError(version.stdout + version.stderr)
    print(version.stdout.strip(), flush=True)
    for number, task in enumerate(TASKS):
        for kind in ("starters", "checkpoints"):
            path = BUNDLE / kind / task.filename
            expected = render(task, completed=kind == "checkpoints")
            if path.read_text(encoding="utf-8") != expected:
                raise RuntimeError(
                    f"Bundle drift: {path.relative_to(ROOT)}; "
                    "run python3 scripts/browser_workshop.py generate"
                )
            scan(path)
            result = compile_file(path)
            output = result.stdout + result.stderr
            should_pass = kind == "checkpoints" or number == 0
            if should_pass and result.returncode:
                raise RuntimeError(output)
            if not should_pass:
                reason = "unsolved goals" if number < 5 else "Tactic `rfl` failed"
                if result.returncode == 0 or reason not in output:
                    raise RuntimeError(f"Unexpected starter result: {path}\n{output}")
                if number == 5:
                    print("Expected Task 05 rejection:\n" + output.strip(), flush=True)
        print(
            f"OK {task.title}: checkpoint accepted; starter behavior checked",
            flush=True,
        )
    print("BROWSER_WORKSHOP_OK (6 checkpoints; 5 expected starter rejections)")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("list", help="List the six browser tasks")
    show = commands.add_parser("show", help="Print a complete paste-ready Lean file")
    show.add_argument("task", choices=[f"{n:02}" for n in range(6)])
    show.add_argument(
        "--completed", action="store_true", help="Show the slide checkpoint"
    )
    check = commands.add_parser(
        "check", help="Rehearse the bundle, or check one edited file"
    )
    check.add_argument("file", nargs="?", type=Path)
    commands.add_parser(
        "generate", help="Maintainer: regenerate from unchanged shared models"
    )
    args = parser.parse_args()
    if args.command == "list":
        for task in TASKS:
            print(f"{task.title}\n  course/browser/starters/{task.filename}")
    elif args.command == "show":
        kind = "checkpoints" if args.completed else "starters"
        print((BUNDLE / kind / TASKS[int(args.task)].filename).read_text(), end="")
    elif args.command == "generate":
        for task in TASKS:
            for kind in ("starters", "checkpoints"):
                directory = BUNDLE / kind
                directory.mkdir(parents=True, exist_ok=True)
                (directory / task.filename).write_text(
                    render(task, completed=kind == "checkpoints"), encoding="utf-8"
                )
    elif args.file is not None:
        path = args.file.resolve()
        if path.suffix != ".lean" or not path.is_file():
            raise RuntimeError("Pass an existing .lean file")
        scan(path)
        result = compile_file(path)
        print(result.stdout + result.stderr, end="")
        if result.returncode:
            raise RuntimeError("Candidate rejected by Lean")
        print(f"BROWSER_FILE_OK {path}")
    else:
        check_bundle()


if __name__ == "__main__":
    try:
        main()
    except (OSError, RuntimeError, subprocess.TimeoutExpired) as error:
        print(f"[browser workshop] error: {error}", file=sys.stderr)
        sys.exit(1)
